/**
 * Преобразует произвольную строку в число в диапазоне [min, max].
 * Используется, например, чтобы назначить "случайное", но детерминированное число для строки.
 *
 * @param {string} str - входная строка (например, ID фильма или видео)
 * @param {number} min - минимальное число диапазона (включительно)
 * @param {number} max - максимальное число диапазона (включительно)
 * @returns {number} число в диапазоне [min, max]
 */
export default function stringToNumberInRange(str, min = 1, max = 100) {
    // вычисляем простой числовой "хэш" из строки
    // складываем коды всех символов строки, умножая каждый на позицию
    // Это даёт одно и то же число для одной и той же строки
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
        // str.charCodeAt(i) возвращает числовой код символа
        // Умножаем на i+1, чтобы порядок символов влиял на результат
        hash += str.charCodeAt(i) * (i + 1);
    }

    // определяем длину диапазона чисел
    const range = max - min + 1; // например, 100 - 1 + 1 = 100

    // используем остаток от деления (mod) для сжатия числа в диапазон [0, range-1]
    // hash % range может быть отрицательным, если hash отрицательный
    // Чтобы гарантировать положительное число, добавляем range и снова берём остаток
    const normalized = ((hash % range) + range) % range;

    // сдвигаем диапазон с [0, range-1] в [min, max]
    const result = normalized + min;

    return result;
}